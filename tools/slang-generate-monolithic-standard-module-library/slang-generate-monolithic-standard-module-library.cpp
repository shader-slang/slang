// slang-generate-monolithic-standard-module-library.cpp
//
// Build-time generator for the optional slang-standard-modules library.
//
// Scans a built standard-module tree, LZ4-compresses every *.slang-module, and
// emits a C++ source that embeds the compressed bytes plus a lookup table keyed
// by import path. This is the standard-modules analogue of slang-embed, but it
// compresses: the serialized standard modules are large and expensive to compile
// as a plain byte-array source, so the payload is compressed first. The matching
// decompression at load uses the same LZ4CompressionSystem (see
// tryLoadStandardModuleFromMonolithicLibrary in source/slang/slang-session.cpp).
//
// Usage:  slang-generate-monolithic-standard-module-library <module-root-dir> <output-cpp>
//
//   <module-root-dir>  the built versioned module dir
//                      (.../<config>/<lib>/slang-standard-module-<version>)
//   <output-cpp>       path of the generated .cpp to write

#include "core/slang-basic.h"
#include "core/slang-compression-system.h"
#include "core/slang-file-system.h"
#include "core/slang-io.h"
#include "core/slang-lz4-compression-system.h"

#include <stdio.h>
#include <string.h>

using namespace Slang;

namespace
{
struct ModuleFile
{
    String key;  // import path, e.g. "slang/numerics/differentiable"
    String path; // absolute path to the .slang-module file
};

struct EnumContext
{
    List<String> dirs;
    List<String> files;
};

void enumCallback(SlangPathType pathType, const char* name, void* userData)
{
    auto ctx = (EnumContext*)userData;
    if (pathType == SLANG_PATH_TYPE_DIRECTORY)
        ctx->dirs.add(name);
    else
        ctx->files.add(name);
}

bool hasSuffix(const String& s, const char* suffix)
{
    const size_t n = strlen(suffix);
    return s.getLength() >= Index(n) && memcmp(s.getBuffer() + s.getLength() - n, suffix, n) == 0;
}

// Recursively collect every .slang-module under 'root', keyed by its path
// relative to 'root' with forward slashes and the ".slang-module" suffix removed.
void collect(ISlangFileSystemExt* fs, const String& root, const String& rel, List<ModuleFile>& out)
{
    String dirPath = rel.getLength() ? Path::combine(root, rel) : root;

    EnumContext ctx;
    fs->enumeratePathContents(dirPath.getBuffer(), enumCallback, &ctx);

    for (auto& f : ctx.files)
    {
        if (!hasSuffix(f, ".slang-module"))
            continue;
        String relFile = rel.getLength() ? (rel + "/" + f) : f;
        ModuleFile mf;
        mf.key = relFile.subString(0, relFile.getLength() - Index(strlen(".slang-module")));
        mf.path = Path::combine(dirPath, f);
        out.add(mf);
    }
    for (auto& d : ctx.dirs)
    {
        String relDir = rel.getLength() ? (rel + "/" + d) : d;
        collect(fs, root, relDir, out);
    }
}
} // namespace

int main(int argc, char** argv)
{
    if (argc != 3)
    {
        fprintf(stderr, "usage: %s <module-root-dir> <output-cpp>\n", argv[0]);
        return 1;
    }
    const String moduleRoot = argv[1];
    const String outputPath = argv[2];

    auto fs = OSFileSystem::getExtSingleton();

    List<ModuleFile> modules;
    collect(fs, moduleRoot, String(), modules);

    if (modules.getCount() == 0)
    {
        fprintf(stderr, "error: no .slang-module files under %s\n", moduleRoot.getBuffer());
        return 1;
    }

    // Deterministic order so the generated file is stable across builds.
    modules.sort([](const ModuleFile& a, const ModuleFile& b) { return a.key < b.key; });

    auto lz4 = LZ4CompressionSystem::getSingleton();
    CompressionStyle style;
    style.m_type = CompressionStyle::Type::BestCompression;

    StringBuilder sb;
    sb << "// Generated by slang-generate-monolithic-standard-module-library -- do not edit.\n";
    sb << "// Source tree: " << moduleRoot << "\n\n";

    StringBuilder table;
    for (Index i = 0; i < modules.getCount(); ++i)
    {
        List<unsigned char> bytes;
        if (SLANG_FAILED(File::readAllBytes(modules[i].path, bytes)))
        {
            fprintf(stderr, "error: cannot read %s\n", modules[i].path.getBuffer());
            return 1;
        }

        ComPtr<ISlangBlob> compressed;
        if (SLANG_FAILED(
                lz4->compress(&style, bytes.getBuffer(), bytes.getCount(), compressed.writeRef())))
        {
            fprintf(stderr, "error: compression failed for %s\n", modules[i].path.getBuffer());
            return 1;
        }

        const auto* data = (const unsigned char*)compressed->getBufferPointer();
        const size_t compressedSize = compressed->getBufferSize();
        const size_t uncompressedSize = (size_t)bytes.getCount();

        StringBuilder symBuilder;
        symBuilder << "g_standardModuleData" << Int64(i);
        String sym = symBuilder.produceString();

        sb << "static const unsigned char " << sym << "[] = {";
        char buf[8];
        for (size_t b = 0; b < compressedSize; ++b)
        {
            snprintf(buf, sizeof(buf), "0x%02x,", data[b]);
            sb << buf;
        }
        sb << "};\n";

        table << "    { \"" << modules[i].key << "\", " << sym << ", sizeof(" << sym << "), "
              << UInt64(uncompressedSize) << " },\n";
    }

    sb << "\nstatic const EmbeddedStandardModule g_standardModules[] = {\n";
    sb << table.getUnownedSlice();
    sb << "};\n\n";
    sb << "static const size_t g_standardModuleCount =\n";
    sb << "    sizeof(g_standardModules) / sizeof(g_standardModules[0]);\n";

    if (SLANG_FAILED(File::writeAllTextIfChanged(outputPath, sb.getUnownedSlice())))
    {
        fprintf(stderr, "error: cannot write %s\n", outputPath.getBuffer());
        return 1;
    }

    fprintf(
        stderr,
        "slang-generate-monolithic-standard-module-library: embedded %d module(s) into %s\n",
        (int)modules.getCount(),
        outputPath.getBuffer());
    return 0;
}
