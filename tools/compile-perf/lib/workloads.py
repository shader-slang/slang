# Suspected-regression features
# --------------------------------------------------------------------------- #

# Call depth within a group. Work scales by *breadth* (number of groups), while
# nesting stays bounded so we don't hit the compiler's type-nesting recursion cap
# (~32 levels in practice). 8 gives ~4× margin and is empirically safe up to
# n=1280 (the largest sweep size used).
_GROUP_DEPTH = 8


def gen_autodiff(n):
    """n differentiable functions arranged in bounded-depth groups, each group
    differentiated in both forward and reverse mode, plus a differentiable
    generic. Stresses the autodiff IR transform (inside linkAndOptimizeIR) and
    the front-end checking of [Differentiable]. Scales by breadth.

    Scaling null: n scales group breadth with depth bounded by _GROUP_DEPTH, so ideal autodiff cost is O(n).
    """
    s = [_HEADER, _buf()]
    s.append("[Differentiable]\n")
    s.append("float leaf(float x) { return x * x + sin(x) * cos(x); }\n\n")
    group_tops = []
    for i in range(n):
        prev = "leaf" if (i % _GROUP_DEPTH == 0) else f"chain_{i - 1}"
        s.append("[Differentiable]\n")
        s.append(
            f"float chain_{i}(float x) {{ return {prev}(x) * 1.0009 + sin(x) * 0.5 - cos(x) * 0.25; }}\n"
        )
        if (i % _GROUP_DEPTH == _GROUP_DEPTH - 1) or i == n - 1:
            group_tops.append(i)
    s.append("\n")
    # A differentiable generic instantiated for float.
    s.append("[Differentiable]\n")
    s.append("T poly<T : IDifferentiable & IFloat>(T x) { return x * x * x + x; }\n\n")
    s.append('[shader("compute")]\n[numthreads(1,1,1)]\n')
    s.append("void computeMain(uint3 tid : SV_DispatchThreadID)\n{\n")
    s.append("    float x = outBuf[tid.x];\n    float acc = 0.0;\n")
    for top in group_tops:
        s.append("    { var dp = diffPair(x, 1.0);\n")
        s.append(f"      bwd_diff(chain_{top})(dp, 1.0); acc += dp.d;\n")
        s.append(f"      acc += fwd_diff(chain_{top})(diffPair(x, 1.0)).d; }}\n")
    s.append("    acc += fwd_diff(poly<float>)(diffPair(x, 1.0)).d;\n")
    s.append("    outBuf[0] = acc;\n}\n")
    return {"autodiff.slang": "".join(s)}


def gen_dynamic_dispatch(n):
    """One interface, n implementations, called through an existential whose
    concrete type is chosen at runtime (defeats static specialization, forcing
    witness-table dynamic dispatch). Stresses dispatch lowering / specializeModule.

    Scaling null: n scales implementations and switch cases; generated code is O(n), so ideal cost is O(n).
    """
    s = [_HEADER, _buf()]
    s.append("[anyValueSize(16)]\ninterface IShape { float eval(float x); }\n\n")
    for i in range(n):
        s.append(
            f"struct Shape{i} : IShape {{ float eval(float x) {{ return x * {i + 1}.0 + {i}.0 + sin(x * {i + 1}.0); }} }}\n"
        )
    s.append("\nfloat dispatch(int id, float x)\n{\n    IShape s;\n    switch (id)\n    {\n")
    for i in range(n):
        s.append(f"    case {i}: s = Shape{i}(); break;\n")
    s.append("    default: s = Shape0(); break;\n    }\n    return s.eval(x);\n}\n\n")
    s.append("float run(IShape s, float x) { return s.eval(x); }\n\n")
    s.append('[shader("compute")]\n[numthreads(1,1,1)]\n')
    s.append("void computeMain(uint3 tid : SV_DispatchThreadID)\n{\n")
    s.append("    float acc = 0.0;\n")
    s.append("    int base = int(tid.x);\n")
    s.append(f"    for (int i = 0; i < {n}; ++i)\n")
    s.append("        acc += dispatch((base + i) % " + str(n) + ", outBuf[0] + float(i));\n")
    s.append("    outBuf[0] = acc;\n}\n")
    return {"dynamic_dispatch.slang": "".join(s)}


def gen_diagnostics(n):
    """n functions that each contain one type error, so the compile emits n
    diagnostics.

    Replaces `diagnostics_clean`, which despite its bucket emitted no errors
    and no warnings at all -- the diagnostic sink was never touched, so what it
    measured was n trivial declarations through the front end, an axis `parse`
    and `conformance` already cover at 13x and 2x the size. Nothing in the
    suite exercised diagnostic production.

    The error is a narrowing vector assignment, chosen because detecting it is
    cheap: the cost this isolates is PRODUCING the diagnostic -- resolving the
    source location, rendering the offending line and caret, formatting and
    writing the message -- not finding it. Against the same shape compiling
    cleanly, `SemanticChecking` is ~40% higher at the same n.

    Compilation stops after the front end, which is the point: no IR lowering
    or codegen dilutes the measurement, and `SemanticChecking` is ~86% of
    `compileInner` at every size. It is also the realistic shape, since a user
    iterating on a broken shader pays exactly this path.

    The manifest marks E30019 as an EXPECTED diagnostic, and bench.py fails the
    workload if it stops appearing -- otherwise this test could rot into a
    clean compile the same way its predecessor did.

    Only `bad_0` is called from `computeMain`; `bad_1..bad_{n-1}` are never
    reached. The O(n) diagnostic count still holds because Slang semantically
    checks every module-level function regardless of whether an entry point
    calls it -- if that stopped being true, this would collapse to a single
    diagnostic instead of n, so the invariant is load-bearing for the scaling
    claim below, not incidental.

    Scaling null: n scales independent diagnostics; ideal cost is O(n).
    """
    s = [_HEADER, _buf()]
    for i in range(n):
        # `float3 t = v;` narrows a float4 -> E30019 "type mismatch in expression".
        s.append(f"float bad_{i}(float4 v) {{ float3 t = v; return t.x + {i % 7}.0; }}\n")
    s.append('\n[shader("compute")]\n[numthreads(1,1,1)]\n')
    s.append("void computeMain()\n{\n    outBuf[0] = bad_0(float4(1, 2, 3, 4));\n}\n")
    return {"diagnostics.slang": "".join(s)}


def gen_existential_aggregate(n):
    """An interface-typed *field* inside a struct (`Scene { IMat m; ... }`), with
    n implementations selected at runtime through a switch. Unlike
    `dynamic_dispatch` (a bare local existential), boxing the existential in an
    aggregate forces `legalizeExistentialTypeLayout` to float the existential
    field out and recompute the parent layout, and feeds specializeModule a
    witness-table-per-case blowup. Stresses specializeModule +
    legalizeExistentialTypeLayout + the downstream simplifyIR. Scales by breadth
    (number of implementations / switch cases).

    Scaling null: n scales cases, each an O(1) body; ideal specialization cost is O(n).
    """
    s = [_HEADER, _buf()]
    s.append("[anyValueSize(16)]\ninterface IMat { float shade(float x); }\n\n")
    for i in range(n):
        s.append(
            f"struct M{i} : IMat {{ float shade(float x) {{ return x * {i + 1}.0 + {i}.0 + sin(x * {i % 7 + 1}.0); }} }}\n"
        )
    s.append("\nstruct Scene { IMat m; float w; }\n\n")
    s.append("float shadeScene(Scene sc, float x) { return sc.m.shade(x) * sc.w; }\n\n")
    s.append('[shader("compute")]\n[numthreads(64,1,1)]\n')
    s.append("void computeMain(uint3 tid : SV_DispatchThreadID)\n{\n")
    s.append("    float acc = 0.0;\n    int base = int(tid.x);\n")
    s.append(f"    for (int i = 0; i < {n}; ++i)\n    {{\n        Scene sc;\n")
    s.append(f"        switch ((base + i) % {n})\n        {{\n")
    for i in range(n):
        s.append(f"        case {i}: sc.m = M{i}(); break;\n")
    s.append("        default: sc.m = M0(); break;\n        }\n")
    s.append("        sc.w = float(i);\n        acc += shadeScene(sc, outBuf[0] + float(i));\n    }\n")
    s.append("    outBuf[0] = acc;\n}\n")
    return {"existential_aggregate.slang": "".join(s)}


# --------------------------------------------------------------------------- #
# Complexity ladder: realistic mixed-feature shader scaled simple -> complex.
# --------------------------------------------------------------------------- #

def gen_complexity_ladder(n):
    """A single shader that ramps *several* realistic dimensions together as n
    grows, modelling how a real shader's compile cost behaves going from simple
    to highly complex — as opposed to the single-axis stressors, which isolate
    one pass. Each step adds: a branchy helper (control flow / SSA + phi), a
    generic call (sema + specialization), a small bounded inner loop, resource
    reads, and a dynamic-dispatch site. Helpers are chained in bounded-depth
    groups (call graph depth) so doubling n roughly doubles total work across
    all of front-end, IR opt, and codegen at once. Sweep this to get the
    holistic complexity->compile-time curve and a floor+slope fit.

    Scaling reference (not a null): several axes co-scale, so the sweep's linear line means 'cost tracks code size' — a user-meaningful reference. Standing super-linearity here is expected; the actionable signal is its release-over-release movement.
    """
    s = [_HEADER]
    s.append("RWStructuredBuffer<float> outBuf;\nStructuredBuffer<float> inBuf;\n\n")
    s.append("interface IOp { float apply(float x); }\n")
    s.append("struct OpAdd : IOp { float apply(float x) { return x + 1.0; } }\n")
    s.append("struct OpMul : IOp { float apply(float x) { return x * 1.5 + 0.25; } }\n")
    s.append("struct OpSq  : IOp { float apply(float x) { return x * x - 0.5; } }\n\n")
    s.append("T gpoly<T : IArithmetic>(T a, T b) { return a * a + b * a + a; }\n\n")
    s.append("float dispatch(int id, float x)\n{\n    IOp o;\n    switch (id % 3)\n    {\n")
    s.append("    case 0: o = OpAdd(); break;\n    case 1: o = OpMul(); break;\n")
    s.append("    default: o = OpSq(); break;\n    }\n    return o.apply(x);\n}\n\n")
    # n branchy helpers in bounded-depth call chains.
    group_tops = []
    for i in range(n):
        prev = f"h_{i - 1}(x)" if (i % _GROUP_DEPTH != 0) else "x"
        s.append(f"float h_{i}(float x)\n{{\n    float t = {prev};\n")
        s.append(f"    if (t > {i % 11}.0) t = t * 1.01 + sin(t + {i % 7}.0);\n")
        s.append("    else t = t - cos(t * 0.5) * 0.25;\n")
        s.append(f"    [MaxIters(4)] for (int k = 0; k < (int(t) & 3) + 1; ++k)\n")
        s.append(f"        t = t * 0.999 + gpoly<float>(t, {i % 5}.0);\n")
        s.append("    return t;\n}\n")
        if (i % _GROUP_DEPTH == _GROUP_DEPTH - 1) or i == n - 1:
            group_tops.append(i)
    s.append('\n[shader("compute")]\n[numthreads(64,1,1)]\n')
    s.append("void computeMain(uint3 tid : SV_DispatchThreadID)\n{\n")
    s.append("    int idx = int(tid.x);\n    float acc = inBuf[idx];\n")
    for j, top in enumerate(group_tops):
        s.append(f"    acc += h_{top}(acc + float({j}));\n")
        s.append(f"    acc += dispatch(idx + {j}, acc);\n")
    s.append("    acc += float(gpoly<int>(idx, idx + 1));\n")
    s.append("    outBuf[idx] = acc;\n}\n")
    return {"complexity_ladder.slang": "".join(s)}


