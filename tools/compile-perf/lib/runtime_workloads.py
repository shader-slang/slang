"""Shared, deterministic shaders for compile and runtime performance experiments.

Complexity changes generated code. Element count is a runtime uniform and never
changes the shader bytes. Every invocation writes a distinct output element.
"""

VERSION = 1
CASES = {
    "arithmetic_basic": "arithmetic",
    "arithmetic_transcendental": "arithmetic",
    "matrix_row": "matrix",
    "matrix_column": "matrix",
    "resources_static": "resources",
    "resources_dynamic": "resources",
    "dispatch_direct": "dispatch",
    "dispatch_generic": "dispatch",
    "dispatch_dynamic": "dispatch",
    "autodiff_primal": "autodiff",
    "autodiff_forward": "autodiff",
    "autodiff_reverse": "autodiff",
    "autodiff_analytic": "autodiff",
    "image_pipeline": "image",
}

COMMON = """// Generated by compile-perf/lib/runtime_workloads.py.
StructuredBuffer<float> inputData;
RWStructuredBuffer<float> outputData;
uniform uint count;
uniform uint width;
uniform uint dispatchWidth;
"""


def kernel(body, declarations=""):
    return COMMON + declarations + """
[shader("compute")]
[numthreads(64, 1, 1)]
void computeMain(uint3 tid : SV_DispatchThreadID)
{
    uint i = tid.x + tid.y * dispatchWidth;
    if (i >= count) return;
""" + body + "\n}\n"


def generate(case, complexity):
    if case not in CASES:
        raise ValueError(f"unknown runtime case: {case}")
    if not 1 <= complexity <= 64:
        raise ValueError("complexity must be between 1 and 64")
    n = complexity
    family = CASES[case]
    if family == "arithmetic":
        expression = ("x * 0.91 + 0.03" if case.endswith("basic") else
                      "sin(x) * 0.4 + cos(x * 0.7) * 0.2 + 0.1")
        body = "    float x = inputData[i];\n"
        body += f"    x = {expression};\n" * n
        body += "    outputData[i] = x;"
        return {"main.slang": kernel(body)}
    if family == "matrix":
        layout = "row_major" if case.endswith("row") else "column_major"
        declarations = (f"struct MatrixData {{ {layout} float4x4 value; }};\n"
                        "StructuredBuffer<MatrixData> matrices;\n")
        body = ("    float x = inputData[i];\n"
                "    float4 v = float4(x, x + 0.1, x + 0.2, x + 0.3);\n"
                "    float4x4 m = matrices[i % 16].value;\n")
        body += "    v = mul(m, v);\n" * n
        body += "    outputData[i] = dot(v, float4(1, 2, 3, 4));"
        return {"main.slang": kernel(body, declarations)}
    if family == "resources":
        declarations = f"StructuredBuffer<float> resources[{n}];\n"
        body = "    float x = 0;\n"
        if case.endswith("dynamic"):
            # Uniform runtime indexing isolates descriptor-address lowering
            # without requiring nonuniform descriptor indexing on every GPU.
            body += f"    uint base = uint(inputData[0] * 1000) % {n};\n"
        for j in range(n):
            index = f"(base + {j}) % {n}" if case.endswith("dynamic") else str(j)
            body += f"    x += resources[{index}][i % 256];\n"
        body += "    outputData[i] = x;"
        return {"main.slang": kernel(body, declarations)}
    if family == "dispatch":
        declarations = "[anyValueSize(16)] interface IMaterial { float eval(float x); };\n"
        for j in range(n):
            declarations += (f"struct Material{j} : IMaterial {{ float eval(float x) "
                             f"{{ return x * 0.75 + {j + 1}.0 * 0.005; }} }};\n")
        declarations += "float genericEval<T : IMaterial>(T m, float x) { return m.eval(x); }\n"
        declarations += "float evaluate(uint id, float x) {\n"
        if case.endswith("dynamic"):
            declarations += "    IMaterial m;\n    switch (id) {\n"
            for j in range(n):
                declarations += f"    case {j}: m = Material{j}(); break;\n"
            declarations += "    default: m = Material0(); break;\n    }\n    return m.eval(x);\n}\n"
        else:
            declarations += "    switch (id) {\n"
            for j in range(n):
                value = (f"genericEval(Material{j}(), x)" if case.endswith("generic")
                         else f"Material{j}().eval(x)")
                declarations += f"    case {j}: return {value};\n"
            declarations += "    default: return Material0().eval(x);\n    }\n}\n"
        body = "    float x = inputData[i];\n"
        for j in range(n):
            body += f"    x = evaluate((i + {j}) % {n}, x);\n"
        body += "    outputData[i] = x;"
        return {"main.slang": kernel(body, declarations)}
    if family == "autodiff":
        declarations = "[Differentiable] float function(float x) {\n"
        declarations += "    x = 0.8 * x + 0.05 * x * x;\n" * n
        declarations += "    return x;\n}\n"
        body = "    float x = inputData[i];\n"
        variant = case.split("_")[1]
        if variant == "primal":
            body += "    outputData[i] = function(x);"
        elif variant == "forward":
            body += "    outputData[i] = fwd_diff(function)(diffPair(x, 1.0)).d;"
        elif variant == "reverse":
            body += "    var p = diffPair(x, 0.0);\n    bwd_diff(function)(p, 1.0);\n    outputData[i] = p.d;"
        else:
            body += "    float d = 1.0;\n"
            body += "    d *= 0.8 + 0.1 * x; x = 0.8 * x + 0.05 * x * x;\n" * n
            body += "    outputData[i] = d;"
        return {"main.slang": kernel(body, declarations)}
    # Buffer-backed images keep the initial application case usable on every
    # compute backend. Each pass has a distinct output buffer, with RHI barriers.
    result = {}
    for direction in ("horizontal", "vertical"):
        body = "    uint x = i % width; uint y = i / width; uint height = count / width;\n    float v = 0;\n"
        for offset in range(-n, n + 1):
            index = (f"y * width + uint((int(x) + {offset} + int(width)) % int(width))"
                     if direction == "horizontal" else
                     f"uint((int(y) + {offset} + int(height)) % int(height)) * width + x")
            body += f"    v += inputData[{index}];\n"
        body += f"    outputData[i] = v / {2 * n + 1}.0;"
        result[f"{direction}.slang"] = kernel(body)
    result["tone.slang"] = kernel("    float x = inputData[i];\n    outputData[i] = x / (1.0 + x);")
    return result


def compile_specs(spec_type):
    """Opt-in compile-perf cases, one entry point per stage of the same corpus."""
    result = []
    for case, family in CASES.items():
        for filename in generate(case, 4):
            stage = filename.removesuffix(".slang")
            name = "runtime_" + case + ("_" + stage if family == "image" else "")

            def gen(n, case=case, filename=filename):
                return {filename: generate(case, n)[filename]}

            result.append(spec_type(
                name=name, bucket="runtime_paired", default_size=4, gen=gen,
                main_file=filename, extra_flags=["-target", "spirv", "-emit-spirv-directly", "-O3"],
                sweep_sizes=[2, 4, 8, 16], primary_timers=["compileInner", "linkAndOptimizeIR"],
            ))
    return result
