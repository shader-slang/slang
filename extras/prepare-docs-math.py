"""Vendor the pinned KaTeX browser distribution from an npm archive.

Download without running package scripts:
    npm pack katex@0.19.1 --ignore-scripts --pack-destination .temp
Then:
    python extras/prepare-docs-math.py .temp/katex-0.19.1.tgz
"""

import argparse
import base64
import hashlib
from pathlib import Path
import tarfile


VERSION = "0.19.1"
INTEGRITY = "jG8uKntjSEcm2EpQOh0XturpPuuC9r3Sq5HLHdsFdWZT27E672SF19QEi+of0/YeOy15lDgRhKvr5614uRrEfA=="


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    args = parser.parse_args()
    digest = base64.b64encode(hashlib.sha512(args.archive.read_bytes()).digest()).decode()
    if digest != INTEGRITY:
        parser.error(f"Archive does not match the pinned KaTeX {VERSION} SHA-512 integrity")

    root = Path(__file__).resolve().parents[1] / "docs/heterogeneity/vendor/katex"
    with tarfile.open(args.archive, "r:gz") as archive:
        for member in archive.getmembers():
            if member.name == "package/LICENSE":
                relative = Path("LICENSE")
            elif member.name in ("package/dist/katex.min.js", "package/dist/katex.min.css"):
                relative = Path(member.name).relative_to("package/dist")
            elif member.name.startswith("package/dist/fonts/") and member.isfile():
                relative = Path(member.name).relative_to("package/dist")
            else:
                continue
            destination = (root / relative).resolve()
            if not destination.is_relative_to(root.resolve()):
                parser.error(f"Archive path escapes the output directory: {member.name}")
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(archive.extractfile(member).read())
    (root / "VERSION.txt").write_text(
        f"KaTeX {VERSION}\nhttps://katex.org/\n"
        f"Source: https://registry.npmjs.org/katex/-/katex-{VERSION}.tgz\n"
        f"Archive integrity: sha512-{INTEGRITY}\n"
        "Generated by extras/prepare-docs-math.py; see LICENSE for redistribution terms.\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
